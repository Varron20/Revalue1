package com.example.myapplication.Clothing;

public class ClothingItem {
    public String type, material, color, date, status;

    public ClothingItem(String type, String material, String color, String date, String status) {
        this.type = type;
        this.material = material;
        this.color = color;
        this.date = date;
        this.status = status;
    }
}
